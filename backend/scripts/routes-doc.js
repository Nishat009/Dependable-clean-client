// Writes docs/ROUTES.md from the routes the app actually registers, with the guard on each one.
// backend/test/security.test.js fails if the file and the code ever disagree. Run: npm run docs:routes
const fs = require('node:fs');
const path = require('node:path');
const { createApp } = require('../app');
const { createDemoDb } = require('../demoDb');

const app = createApp(createDemoDb(), { demoMode: true, demoEnabled: true, clientOrigins: [], authRateLimit: 20, trustProxy: 0 });
const routes = app.router.stack.filter((layer) => layer.route).flatMap((layer) => Object.keys(layer.route.methods).map((method) => ({
  method: method.toUpperCase(), path: layer.route.path, guard: layer.route.stack.map((item) => item.handle.guard).filter(Boolean).at(-1) || 'public'
})));
const row = (r) => `| \`${r.method} ${r.path}\` | ${r.guard === 'public' ? 'public' : '`' + r.guard + '`'} |`;
const writes = routes.filter((r) => r.method !== 'GET'), reads = routes.filter((r) => r.method === 'GET');

const doc = `# API routes and their guards

Generated by \`npm run docs:routes\` from the routes registered in \`backend/app.js\`. \`npm test\` fails if this file and the code disagree.

## Guards

| Guard | Who passes |
| --- | --- |
| \`requireUser\` | Any signed-in, active account. The account, its role and its token version are loaded from the database on every request, so deactivation and revoked tokens apply at once. |
| \`requireCustomer\` | Customers (permission \`book\`). |
| \`requireSupport\` | Customers, staff, sub admins and the owner (permission \`support\`). Each ticket is also scoped to its customer, its assigned staff member or an admin. |
| \`requireStaff\` | Staff, sub admins and the owner (permission \`jobs\`). Staff are further limited to jobs assigned to them. |
| \`requireSuperAdmin\` | Sub admins and the owner (permission \`manage\`). |
| \`requireTeamAdmin\` | The owner only (permission \`team\`). |
| public | No sign-in. The only public writes are \`/signup\`, \`/login\`, \`/demoLogin\` and \`/setupAccount\`, and all four are rate limited per IP address and email. |

Roles and permissions are defined in \`backend/permissions.js\`; the guards are in \`backend/middleware.js\`.

## Ownership on lookups by id

| Route | Scope applied in the database filter |
| --- | --- |
| \`GET /bookings/:id\` | Admins: any booking. Staff: \`staffEmail\` is theirs. Customers: \`email\` is theirs. Otherwise 403. |
| \`PATCH /updateOrderList/:id\` | Admins: any booking. Staff: only jobs with their \`staffEmail\`. Customers: 403 from the guard. |
| \`POST /bookings/:id/request\` | Only the customer whose \`email\` is on the booking. |
| \`POST /addReview\` | Only the customer whose \`email\` is on the completed booking. |
| \`/support/:id\`, \`/support/:id/messages\` | Admins: any ticket. Staff: tickets assigned to them. Customers: their own ticket. Otherwise 403. |
| \`PATCH /profile\` | Always the signed-in account; the body cannot name another user. |

Every request body, query and path parameter is rejected with 400 if any key starts with \`$\` or contains a dot, so MongoDB operators cannot be injected.

## Create, update and delete routes (${writes.length})

| Route | Guard |
| --- | --- |
${writes.map(row).join('\n')}

## Read routes (${reads.length})

| Route | Guard |
| --- | --- |
${reads.map(row).join('\n')}
`;

fs.mkdirSync(path.resolve(__dirname, '../../docs'), { recursive: true });
fs.writeFileSync(path.resolve(__dirname, '../../docs/ROUTES.md'), doc);
console.log(`docs/ROUTES.md: ${writes.length} write routes, ${reads.length} read routes.`);
